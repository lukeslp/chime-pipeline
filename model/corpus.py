def split_for(source: str, unit: str) -> str:
    """The split for a dialogue (or, without one, a line): hashed per source."""
    bucket = xxhash.xxh64_intdigest(f"{source}\t{unit}".encode("utf-8"), seed=7) % 100
    if bucket < 98:
        return "train"
    return "dev" if bucket == 98 else "test"


@dataclass
class SourceStats:
    raw: int = 0
    filtered: Counter = field(default_factory=Counter)
    exact_dup: int = 0
    template_dup: int = 0
    near_dup: int = 0
    kept: int = 0
    words: int = 0
    per_split: Counter = field(default_factory=Counter)
    dialogues: set = field(default_factory=set)


NUMBER_WORDS = {1: "one", 2: "two", 3: "three", 4: "four", 5: "five", 6: "six"}
SHORT_NAMES = {"nus": "NUS SMS", "taskmaster": "Taskmaster-1", "oasst2": "OASST2",
               "taskmaster3": "Taskmaster-3", "soda": "SODA"}


def _count_words(n: int) -> str:
    return NUMBER_WORDS.get(n, str(n))


def _join(names: list[str]) -> str:
    return names[0] if len(names) == 1 else ", ".join(names[:-1]) + " and " + names[-1]


def human_written_note(sources: list[str]) -> str:
    """One sentence on who wrote what, for stats.json and LICENSES.md."""
    human = [SHORT_NAMES[k] for k in sources if SOURCES[k].human_written]
    synthetic = [SHORT_NAMES[k] for k in sources if not SOURCES[k].human_written]
    parts = []
    if synthetic:
        parts.append(f"{_join(synthetic)} {'is' if len(synthetic) == 1 else 'are'} synthetic dialogue "
                     "generated by a language model")
    if human:
        parts.append(f"only {_join(human)} {'was' if len(human) == 1 else 'were'} typed by people")
    return "; ".join(parts)


def licenses_markdown(manifests: dict[str, dict], sources: list[str] | None = None) -> str:
    """LICENSES.md for one build: only the sources it used, in build order."""
    sources = list(sources or manifests or PRESETS["v2"][0])
    licenses = sorted({SOURCES[k].license for k in sources})
    dates = sorted({SOURCES[k].verified_on for k in sources})
    human = [k for k in sources if SOURCES[k].human_written]
    out = [
        "# Corpus sources and licenses",
        "",
        f"Checked on {' and '.join(dates)} against the pages named under each entry (the date is on each one), "
        "before anything was downloaded. Every source below is under a license that allows redistribution and "
        f"derivative works with attribution ({', '.join(licenses)}). Anything with a NonCommercial clause, an "
        "unclear license or no license was refused, and so was anything written by a model and offered as "
        "human text.",
        "",
        f"{_count_words(len(human)).capitalize()} of the {_count_words(len(sources))} sources are human-written "
        f"({_join([SHORT_NAMES[k] for k in human]) if human else 'none'})"
        + "".join(f"; {SHORT_NAMES[k]} is synthetic dialogue generated by a language model"
                  for k in sources if not SOURCES[k].human_written)
        + ". The human-written share of the assembled corpus is stated in `stats.json` under `human_written`.",
        "",
    ]
    for key in sources:
        s = SOURCES[key]
        m = manifests.get(key, {})
        out += [
            f"## {s.name}",
            "",
            f"- License: {s.license} ({s.license_url})",
            f"- Where: {s.homepage}",
            f"- Version: {s.version}",
            f"- Taken: {s.how}",
            f"- Origin: {s.origin}",
            f"- License read at: {s.verified_by}",
            f"- Verified on: {s.verified_on}",
        ]
        if s.terms_note:
            out.append(f"- Terms beyond the license: {s.terms_note}")
        for f in m.get("files", []):
            out.append(f"- File: `{f['file']}` sha256 `{f['sha256']}`")
        out.append("")
    out += ["## Refused", ""]
    for what, why in REFUSED:
        out.append(f"- {what}: {why}")
    out += ["", "## Attribution", ""]
    for key in sources:
        out.append(f"- {SHORT_NAMES[key]}: {SOURCES[key].attribution}")
    out += [
        "",
        f"The assembled corpus is a derivative of these {_count_words(len(sources))} sources and is shared under "
        "the terms above; the per-line source file next to each split says which source every line came from.",
        "",
    ]
    return "\n".join(out)


def write_manifest(out_dir: Path, sources: list[str], manifests: dict[str, dict]) -> None:
    with open(out_dir / "manifest.json", "w", encoding="utf-8") as f:
        json.dump(
            {
                "verified_on": max(SOURCES[k].verified_on for k in sources),
                "sources": {k: {**SOURCES[k].__dict__, **manifests.get(k, {})} for k in sources},
                "refused": [{"what": w, "why": y} for w, y in REFUSED],
            },
            f,
            indent=2,
        )
    with open(out_dir / "LICENSES.md", "w", encoding="utf-8") as f:
        f.write(licenses_markdown(manifests, sources))


def check_output_dir(out_dir: Path, sources: list[str]) -> None:
    """Refuse to rebuild a corpus directory from a different source list.

    The default output of each preset is a published corpus; a run with other
    sources and no --out of its own would otherwise replace it silently.
    """
    path = out_dir / "manifest.json"
    if not path.exists():
        return
    with open(path, encoding="utf-8") as f:
        old = list(json.load(f).get("sources", {}))
    if old != sources:
        raise SystemExit(f"{out_dir} holds a corpus built from {old}; this run asks for {sources}. "
                         "Give it its own --out.")


