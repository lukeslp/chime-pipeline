Utterance = tuple[str, frozenset[str] | None, str]


def sha256_of(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def download(url: str, dest: Path, sha256: str) -> Path:
    if dest.exists() and sha256_of(dest) == sha256:
        return dest
    import urllib.request

    dest.parent.mkdir(parents=True, exist_ok=True)
    tmp = dest.with_suffix(dest.suffix + ".part")
    with urllib.request.urlopen(url) as r, open(tmp, "wb") as f:
        while chunk := r.read(1 << 20):
            f.write(chunk)
    got = sha256_of(tmp)
    if got != sha256:
        tmp.unlink()
        raise SystemExit(f"{url}: sha256 {got} != expected {sha256}; refusing to use it")
    tmp.rename(dest)
    return dest


def hf_snapshot(key: str) -> Path:
    from huggingface_hub import snapshot_download

    repo, rev = HF_REVISIONS[key]
    return Path(snapshot_download(repo_id=repo, repo_type="dataset", revision=rev))


def hf_file(key: str) -> tuple[Path, dict]:
    """One pinned file from a Hub dataset, refused unless its sha256 matches."""
    from huggingface_hub import hf_hub_download

    repo, rev, name, sha256 = HF_FILES[key]
    path = Path(hf_hub_download(repo_id=repo, filename=name, repo_type="dataset", revision=rev))
    got = sha256_of(path)
    if got != sha256:
        raise SystemExit(f"{repo}@{rev}/{name}: sha256 {got} != expected {sha256}; refusing to use it")
    return path, {"file": name, "sha256": sha256, "repo": repo, "revision": rev}


def soda_names(row: dict) -> frozenset[str]:
    names = set()
    for n in list(row.get("speakers") or []) + [row.get("PersonX"), row.get("PersonY"), row.get("PersonZ")]:
        if n:
            for w in WORD_RE.findall(n):
                names.add(_norm(w))
    return frozenset(names)


def read_soda(manifest: dict) -> Iterator[Utterance]:
    root = hf_snapshot("soda")
    files = sorted(glob.glob(str(root / "*.parquet")))
    manifest["files"] = [{"file": os.path.basename(f), "sha256": sha256_of(Path(f))} for f in files]
    manifest["dialogue_id"] = "original_index column (one row = one dialogue)"
    cols = ["dialogue", "speakers", "PersonX", "PersonY", "PersonZ", "original_index"]
    for f in files:
        pf = pq.ParquetFile(f)
        for batch in pf.iter_batches(batch_size=4096, columns=cols):
            for row in batch.to_pylist():
                names = soda_names(row)
                group = f"soda:{row['original_index']}"
                for turn in row["dialogue"]:
                    yield group, names, turn


def read_nus(manifest: dict) -> Iterator[Utterance]:
    zip_path = download(NUS_ZIP_URL, DATA_ROOT / "downloads" / "nus_smsCorpus_en_xml_2015.03.09_all.zip", NUS_ZIP_SHA256)
    manifest["files"] = [{"file": zip_path.name, "sha256": NUS_ZIP_SHA256, "url": NUS_ZIP_URL}]
    manifest["dialogue_id"] = "none: every message is its own unit"
    with zipfile.ZipFile(zip_path) as z:
        name = [n for n in z.namelist() if n.endswith(".xml")][0]
        data = z.read(name)
    langs: Counter = Counter()
    placeholders: Counter = Counter()
    manifest["languages"] = langs
    manifest["placeholders_removed"] = placeholders
    for _, elem in ElementTree.iterparse(io.BytesIO(data), events=("end",)):
        if elem.tag != "message":
            continue
        prof = elem.find("messageProfile")
        lang = prof.get("language") if prof is not None else None
        langs[lang] += 1
        if lang == "en":
            text = elem.findtext("text")
            if text:
                # The release already redacts numbers, emails, URLs and names to
                # <#>, <DECIMAL>, <EMAIL>, <URL>, <name> and so on; drop the tags.
                placeholders.update(NUS_PLACEHOLDER_RE.findall(text))
                yield "", None, NUS_PLACEHOLDER_RE.sub(" ", text)
        elem.clear()


def taskmaster_user_turns(dialogs: list[dict], key: str, speakers: Counter) -> Iterator[Utterance]:
    """The customer side of Taskmaster self dialogs: `USER` in TM-1, `user` in TM-3."""
    for d in dialogs:
        group = f"{key}:{d['conversation_id']}"
        for u in d["utterances"]:
            speakers[u["speaker"]] += 1
            if u["speaker"].upper() == "USER":
                yield group, None, u["text"]


def read_taskmaster(manifest: dict) -> Iterator[Utterance]:
    path = download(TASKMASTER_URL, DATA_ROOT / "downloads" / "taskmaster1_self-dialogs.json", TASKMASTER_SHA256)
    manifest["files"] = [{"file": path.name, "sha256": TASKMASTER_SHA256, "url": TASKMASTER_URL}]
    manifest["dialogue_id"] = "conversation_id"
    with open(path, encoding="utf-8") as f:
        dialogs = json.load(f)
    speakers: Counter = Counter()
    manifest["speakers"] = speakers
    yield from taskmaster_user_turns(dialogs, "taskmaster", speakers)


def read_taskmaster3(manifest: dict) -> Iterator[Utterance]:
    files = []
    for name, sha256 in TASKMASTER3_SHA256.items():
        files.append(download(TASKMASTER3_URL + name, DATA_ROOT / "downloads" / "taskmaster3" / name, sha256))
    manifest["files"] = [{"file": f"taskmaster3/{p.name}", "sha256": TASKMASTER3_SHA256[p.name],
                          "url": TASKMASTER3_URL + p.name} for p in files]
    manifest["dialogue_id"] = "conversation_id"
    speakers: Counter = Counter()
    manifest["speakers"] = speakers
    for path in files:
        with open(path, encoding="utf-8") as f:
            dialogs = json.load(f)
        yield from taskmaster_user_turns(dialogs, "taskmaster3", speakers)


def oasst2_prompter_turns(lines: Iterable[str], counts: Counter) -> Iterator[Utterance]:
    """English prompter turns typed by people: not synthetic, not deleted, not failed in review.

    The unit is the message tree, so every prompt and follow-up of one
    conversation lands in the same split.
    """
    for line in lines:
        m = json.loads(line)
        if m.get("role") != "prompter":
            counts["assistant"] += 1
        elif m.get("lang") != "en":
            counts["not_english"] += 1
        elif m.get("synthetic"):
            counts["synthetic"] += 1
        elif m.get("deleted"):
            counts["deleted"] += 1
        elif m.get("review_result") is False:
            counts["failed_review"] += 1
        else:
            counts["taken"] += 1
            yield f"oasst2:{m['message_tree_id']}", None, m["text"]


def read_oasst2(manifest: dict) -> Iterator[Utterance]:
    path, info = hf_file("oasst2")
    manifest["files"] = [info]
    manifest["dialogue_id"] = "message_tree_id"
    counts: Counter = Counter()
    manifest["messages"] = counts
    with gzip.open(path, "rt", encoding="utf-8") as f:
        yield from oasst2_prompter_turns(f, counts)


