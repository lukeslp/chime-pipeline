#!/usr/bin/env python3
"""Assemble the LocalType next-word corpus from permissively licensed sources.

Everything this script downloads or writes lives under the data root
(default ~/.local/share/localtype-model), never under the repo:

    <root>/hf-cache/          Hugging Face hub cache (HF_HOME / HF_HUB_CACHE)
    <root>/downloads/         GitHub files (NUS SMS zip, Taskmaster JSON)
    <root>/corpus/            the v2 build: train.txt dev.txt test.txt,
                              *.sources.txt, stats.json, manifest.json, LICENSES.md
    <root>/corpus-v3/         the v3 build, same layout, two more human sources

Pipeline: read each source -> keep the human/user side of every dialog ->
one utterance per line, whitespace normalized -> drop lines with URLs, emails,
phone numbers, credential-looking strings, code or non-Latin script ->
exact dedupe (normalized key) -> template dedupe (the same key with names
masked, lines of 8+ words only) -> near dedupe (MinHash over word 3-shingles,
6 bands x 8 rows, first occurrence wins) -> 98/1/1 split by a per-source
stable hash of the DIALOGUE the line came from -> write.

Every source except SODA is human-written (NUS SMS, the Taskmaster-1 and
Taskmaster-3 self dialogs, OASST2 prompter turns); SODA is synthetic dialogue
generated by a language model. stats.json states the human-written share by
line and by word.

Two presets name the builds. v2 (the default) is NUS, Taskmaster-1 and SODA
into <root>/corpus, exactly as published on 2026-09-25. v3 adds OASST2 and
Taskmaster-3 and writes <root>/corpus-v3. The human sources come first in
both, in the same order, so the NUS and Taskmaster-1 lines of v3 are the v2
lines, split the same way.

Usage:
    python corpus.py                # v2, written to <root>/corpus
    python corpus.py --preset v3    # v3, written to <root>/corpus-v3
    python corpus.py --limit 20000 --out <root>/scratch/corpus-smoke
                                    # smoke run, capped per source
    python corpus.py --sources nus,taskmaster --out <root>/scratch/corpus-human

A smoke or partial run needs its own --out: the default is the preset's
corpus, and a run replaces its train/dev/test files in place. A run refuses to
write into a corpus directory that was built from other sources.
"""

