# Stricter than AdaptiveNgramModel.WORD_REGEX ([\p{L}][\p{L}'’-]*): a letter
# followed by letters only, so contractions and hyphenated words split
# ("don't" -> "don", "t"). Kept as-is so the published corpus, its stats and
# its dedupe keys reproduce; tokenize.py and cifg.py follow the device rule.
WORD_RE = re.compile(r"[^\W\d_][^\W\d_'’-]*")
WS_RE = re.compile(r"\s+")
CONTROL_RE = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]")

URL_RE = re.compile(
    r"(?i)(?:https?://|ftp://|www\.)\S+"
    r"|\b[a-z0-9][a-z0-9-]*\.(?:com|net|org|io|gov|edu|co|uk|sg|de|fr|ca|au|ly|me|"
    r"info|biz|tv|app|dev|ai|us|in)\b(?:/\S*)?"
)
EMAIL_RE = re.compile(r"[\w.+-]+@[\w-]+(?:\.[\w-]+)+")
PHONE_RE = re.compile(r"(?<![\w-])\+?\d[\d\s().-]{5,}\d(?![\w-])")
CREDENTIAL_RES = [
    re.compile(r"(?i)\b(?:password|passwd|pwd|passcode|pin\s*code|api[_ -]?key|access[_ -]?token|secret[_ -]?key|auth[_ -]?token)\b\s*(?:is|[:=])"),
    re.compile(r"\b[0-9a-fA-F]{32,}\b"),
    re.compile(r"\b(?:sk|pk|rk)-[A-Za-z0-9]{16,}\b"),
    re.compile(r"\bAKIA[0-9A-Z]{16}\b"),
    re.compile(r"\bgh[pousr]_[A-Za-z0-9]{20,}\b"),
    re.compile(r"\bxox[abprs]-[A-Za-z0-9-]{10,}\b"),
    re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY"),
    re.compile(r"\b(?=[A-Za-z0-9_\-]*\d)(?=[A-Za-z0-9_\-]*[A-Za-z])[A-Za-z0-9_\-]{24,}\b"),
]
CODE_RE = re.compile(r"```|</?[a-z]+[^>]*>|[{};]\s*$|^\s*(?:def |class |import |#include|SELECT |\$ )")

MAX_CHARS = 600
MAX_JUNK_RATIO = 0.4
PLAIN_PUNCT = set(".,!?'’-:;()\"…")


def _is_latin_letter(cp: int, _cache: dict[int, bool] = {}) -> bool:
    hit = _cache.get(cp)
    if hit is None:
        ch = chr(cp)
        if ch.isalpha():
            name = unicodedata.name(ch, "")
            hit = name.startswith("LATIN") or "LETTER" not in name
        else:
            hit = True
        _cache[cp] = hit
    return hit


def clean(text: str) -> str:
    """Whitespace-normalize one utterance into a single line."""
    text = html.unescape(text)
    text = unicodedata.normalize("NFC", text)
    text = CONTROL_RE.sub(" ", text)
    return WS_RE.sub(" ", text).strip()


def filter_reason(line: str) -> str | None:
    """Return why a line is dropped, or None to keep it."""
    if not line:
        return "empty"
    if len(line) > MAX_CHARS:
        return "too_long"
    if URL_RE.search(line):
        return "url"
    if EMAIL_RE.search(line):
        return "email"
    m = PHONE_RE.search(line)
    if m and sum(c.isdigit() for c in m.group(0)) >= 7:
        return "phone"
    for rx in CREDENTIAL_RES:
        if rx.search(line):
            return "credential"
    if CODE_RE.search(line):
        return "code"
    words = WORD_RE.findall(line)
    if not words:
        return "no_words"
    junk = sum(1 for c in line if not (c.isalpha() or c == " " or c in PLAIN_PUNCT))
    if junk / len(line) > MAX_JUNK_RATIO:
        return "mostly_symbols"
    for ch in line:
        if ch.isalpha() and not _is_latin_letter(ord(ch)):
            return "non_latin"
    return None


def _norm(w: str) -> str:
    return w.replace("’", "'").lower()


def normalized_key(line: str) -> str:
    """Key for exact dedupe: lowercase word tokens only."""
    return " ".join(_norm(w) for w in WORD_RE.findall(line))


# --------------------------------------------------------------------------
# Template dedupe: the same key with names masked
# --------------------------------------------------------------------------
#
# SODA is built from templates: "Hey, Anahi. I wanted to talk to you about
# something." recurs with hundreds of names in the slot, and a name swap is not
# a new line for a keyboard. A line's template key masks (a) the names of the
# dialogue's own speakers and characters, when the source knows them, and
# (b) any capitalized word that is not the first word of the line and not a
# form of "I". Lines under MIN_TEMPLATE_TOKENS words are exempt: "Thanks, Mom"
# and "Thanks, Sam" are both real messages and both worth keeping.

MIN_TEMPLATE_TOKENS = 8
NAME_MASK = "<name>"
CAP_RE = re.compile(r"^[A-Z][a-z'’-]*$")
# The apostrophe and hyphen forms here, and the "'s" base in template_key,
# never match under WORD_RE (it splits there); kept so the rule stays right if
# WORD_RE ever follows the device.
I_FORMS = frozenset({"i", "i'm", "i'll", "i'd", "i've", "i-"})


def template_key(line: str, names: frozenset[str] | None = None) -> str | None:
    """The name-masked key, or None when the line is too short for the rule."""
    toks = WORD_RE.findall(line)
    if len(toks) < MIN_TEMPLATE_TOKENS:
        return None
    out = []
    for i, t in enumerate(toks):
        n = _norm(t)
        base = n[:-2] if n.endswith("'s") else n
        if names and (n in names or base in names):
            out.append(NAME_MASK)
        elif i > 0 and CAP_RE.match(t) and n not in I_FORMS and not n.startswith("i'"):
            out.append(NAME_MASK)
        else:
            out.append(n)
    return " ".join(out)


# --------------------------------------------------------------------------
# Near-duplicate detection: MinHash, 48 permutations, 6 bands x 8 rows
# --------------------------------------------------------------------------

NUM_PERM = 48
BANDS = 6
ROWS = NUM_PERM // BANDS
MIN_SHINGLE_TOKENS = 8
_rng = np.random.RandomState(20260925)
# Linear hashes mod 2**64 (uint64 wraparound); odd multipliers so they are bijections.
PERM_A = (_rng.randint(1, 1 << 62, size=NUM_PERM, dtype=np.int64).astype(np.uint64) << np.uint64(1)) | np.uint64(1)
PERM_B = _rng.randint(0, 1 << 62, size=NUM_PERM, dtype=np.int64).astype(np.uint64)
_UNIQUE_BIT = np.uint64(1 << 63)


def band_hashes(tokens: list[str], row_index: int) -> np.ndarray:
    """Six uint64 band hashes; lines too short for shingles get a unique value."""
    if len(tokens) < MIN_SHINGLE_TOKENS:
        return np.full(BANDS, _UNIQUE_BIT | np.uint64(row_index), dtype=np.uint64)
    shingles = {xxhash.xxh64_intdigest(" ".join(tokens[i : i + 3]).encode("utf-8")) for i in range(len(tokens) - 2)}
    h = np.fromiter(shingles, dtype=np.uint64, count=len(shingles))
    # (a * h + b) mod 2**64 for every permutation, then the minimum over shingles
    sig = (h[:, None] * PERM_A[None, :] + PERM_B[None, :]).min(axis=0).reshape(BANDS, ROWS)
    out = np.empty(BANDS, dtype=np.uint64)
    for b in range(BANDS):
        out[b] = xxhash.xxh64_intdigest(sig[b].tobytes()) & ((1 << 63) - 1)
    return out


def near_duplicate_mask(bands: np.ndarray) -> np.ndarray:
    """True for every row that shares a band hash with an earlier row."""
    n = bands.shape[0]
    dup = np.zeros(n, dtype=bool)
    for b in range(BANDS):
        col = bands[:, b]
        _, first_index, inverse = np.unique(col, return_index=True, return_inverse=True)
        dup |= first_index[inverse] != np.arange(n)
    return dup


